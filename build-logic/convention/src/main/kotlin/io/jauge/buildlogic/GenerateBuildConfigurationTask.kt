package io.jauge.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates `BuildConfiguration.kt`, a Kotlin object exposing the public keys and switches of the app to common code.
 *
 * Values come from `local.properties` (ignored by git), and environment variables take precedence so that the Xcode
 * build (which exports the settings of `Config.xcconfig`) and continuous integration can provide them too.
 * Secret keys are refused: the build fails if a RevenueCat secret key (`sk_`) or a Supabase secret key is found.
 */
@CacheableTask
abstract class GenerateBuildConfigurationTask : DefaultTask() {

    /** Resolved configuration values, keyed by property name (for example `jauge.api.baseUrl`). */
    @get:Input
    abstract val values: MapProperty<String, String>

    /**
     * True for a release build of the iOS framework (Xcode `CONFIGURATION=Release`): debug only values (Test Store
     * key, offline mode) are left out of the binary. Android release builds drop them with R8 and `AppEnvironment`.
     */
    @get:Input
    abstract val releaseBuild: Property<Boolean>

    /** Package of the generated object. */
    @get:Input
    abstract val packageName: Property<String>

    /** Directory receiving the generated Kotlin source. */
    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    /** Writes the generated source file. */
    @TaskAction
    fun generate() {
        val resolved = values.get()
        val apiBaseUrl = resolved[API_BASE_URL].orEmpty().ifBlank { DEFAULT_API_BASE_URL }
        val offlineModeValue = resolved[API_OFFLINE_MODE].orEmpty().trim().lowercase()
        val isRelease = releaseBuild.getOrElse(false)
        val offlineMode = offlineModeValue != "false" && !isRelease
        val supabaseUrl = resolved[SUPABASE_URL].orEmpty().trim()
        val supabaseKey = resolved[SUPABASE_PUBLISHABLE_KEY].orEmpty().trim()
        val revenueCatGoogle = resolved[REVENUECAT_GOOGLE_API_KEY].orEmpty().trim()
        val revenueCatApple = resolved[REVENUECAT_APPLE_API_KEY].orEmpty().trim()
        val revenueCatTestStore = if (isRelease) "" else resolved[REVENUECAT_TEST_STORE_API_KEY].orEmpty().trim()

        refuseSecret(REVENUECAT_GOOGLE_API_KEY, revenueCatGoogle, revenueCatGoogle.startsWith("sk_"))
        refuseSecret(REVENUECAT_APPLE_API_KEY, revenueCatApple, revenueCatApple.startsWith("sk_"))
        refuseSecret(REVENUECAT_TEST_STORE_API_KEY, revenueCatTestStore, revenueCatTestStore.startsWith("sk_"))
        refuseSecret(
            SUPABASE_PUBLISHABLE_KEY,
            supabaseKey,
            supabaseKey.startsWith("sb_secret_") || supabaseKey.contains("service_role") || isServiceRoleJwt(supabaseKey),
        )

        val directory = outputDirectory.get().asFile
        directory.deleteRecursively()
        val packageDirectory = directory.resolve(packageName.get().replace('.', '/'))
        packageDirectory.mkdirs()
        packageDirectory.resolve("BuildConfiguration.kt").writeText(
            """
            |// Generated by GenerateBuildConfigurationTask from local.properties. Do not edit.
            |package ${packageName.get()}
            |
            |/**
            | * Build time configuration of the app: public keys and switches read from `local.properties`
            | * (or from environment variables). It never contains a secret key.
            | */
            |public object BuildConfiguration {
            |    /** Base URL of the Jauge API, always ending with a slash. */
            |    public const val API_BASE_URL: String = "${apiBaseUrl.ensureTrailingSlash().escape()}"
            |
            |    /** True when the app must use the built in offline data instead of the real API. */
            |    public const val OFFLINE_MODE: Boolean = $offlineMode
            |
            |    /** URL of the Supabase project, empty when not configured. */
            |    public const val SUPABASE_URL: String = "${supabaseUrl.escape()}"
            |
            |    /** Supabase publishable (public) key, empty when not configured. */
            |    public const val SUPABASE_PUBLISHABLE_KEY: String = "${supabaseKey.escape()}"
            |
            |    /** RevenueCat public SDK key for Google Play (`goog_`), empty when not configured. */
            |    public const val REVENUECAT_GOOGLE_API_KEY: String = "${revenueCatGoogle.escape()}"
            |
            |    /** RevenueCat public SDK key for the App Store (`appl_`), empty when not configured. */
            |    public const val REVENUECAT_APPLE_API_KEY: String = "${revenueCatApple.escape()}"
            |
            |    /** RevenueCat Test Store public SDK key (`test_`), used by debug builds on both platforms. */
            |    public const val REVENUECAT_TEST_STORE_API_KEY: String = "${revenueCatTestStore.escape()}"
            |}
            |""".trimMargin(),
        )
    }

    private fun refuseSecret(name: String, value: String, isSecret: Boolean) {
        if (value.isNotEmpty() && isSecret) {
            throw GradleException(
                "'$name' contains a secret key. Only public SDK keys may be shipped in the app: remove it from " +
                    "local.properties or the environment.",
            )
        }
    }

    /** A legacy Supabase key is a JWT whose payload says `"role":"service_role"` (base64 encoded, so decoded here). */
    private fun isServiceRoleJwt(key: String): Boolean {
        val parts = key.split('.')
        if (parts.size != 3) return false
        val payload = runCatching { String(java.util.Base64.getUrlDecoder().decode(parts[1].trimEnd('='))) }.getOrNull()
        return payload?.replace(" ", "")?.contains("\"role\":\"service_role\"") == true
    }

    private fun String.ensureTrailingSlash(): String = if (endsWith("/")) this else "$this/"

    private fun String.escape(): String = replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

    /** Names of the supported configuration properties. */
    companion object {
        /** Base URL of the API. */
        const val API_BASE_URL = "jauge.api.baseUrl"

        /** `false` to call the real API, anything else (or nothing) keeps the offline mode. */
        const val API_OFFLINE_MODE = "jauge.api.offlineMode"

        /** Supabase project URL. */
        const val SUPABASE_URL = "supabase.url"

        /** Supabase publishable key. */
        const val SUPABASE_PUBLISHABLE_KEY = "supabase.publishableKey"

        /** RevenueCat public key for Google Play. */
        const val REVENUECAT_GOOGLE_API_KEY = "revenuecat.googleApiKey"

        /** RevenueCat public key for the App Store. */
        const val REVENUECAT_APPLE_API_KEY = "revenuecat.appleApiKey"

        /** RevenueCat Test Store public key, used by debug builds only. */
        const val REVENUECAT_TEST_STORE_API_KEY = "revenuecat.testStoreApiKey"

        /** Default API base URL. */
        const val DEFAULT_API_BASE_URL = "https://api.jauge.io/"

        /** Every supported property name. */
        val ALL_KEYS = listOf(
            API_BASE_URL,
            API_OFFLINE_MODE,
            SUPABASE_URL,
            SUPABASE_PUBLISHABLE_KEY,
            REVENUECAT_GOOGLE_API_KEY,
            REVENUECAT_APPLE_API_KEY,
            REVENUECAT_TEST_STORE_API_KEY,
        )

        /**
         * Environment variable name for a property: `JAUGE_` followed by the property in upper snake case, for
         * example `JAUGE_SUPABASE_PUBLISHABLE_KEY` for `supabase.publishableKey` and `JAUGE_API_BASE_URL` for
         * `jauge.api.baseUrl`.
         */
        fun environmentVariableFor(key: String): String {
            val snakeCase = key.removePrefix("jauge.")
                .replace(Regex("([a-z0-9])([A-Z])"), "$1_$2")
                .replace('.', '_')
                .uppercase()
            return "JAUGE_$snakeCase"
        }
    }
}
